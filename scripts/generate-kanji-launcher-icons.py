#!/usr/bin/env python3
"""Regenerate the approved Android launcher resources with Pillow 13.0.0.

Install Pillow 13.0.0 separately, then run this script from any directory.
Use --check to compare the generated bytes without modifying resources.
"""
from io import BytesIO
from pathlib import Path
import argparse
import hashlib
import sys
from PIL import Image, __version__

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'resources/tora-kanji-icon.png'
SOURCE_SHA256 = '084965faf7af9fec2883f33710ec0d01824f66c647969cfff0748bdba9eb1dca'
DENSITIES = (('mdpi', 48, 108), ('hdpi', 72, 162), ('xhdpi', 96, 216), ('xxhdpi', 144, 324), ('xxxhdpi', 192, 432))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if __version__ != '13.0.0':
        sys.exit(f'Pillow 13.0.0 required; found {__version__}')
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != SOURCE_SHA256:
        sys.exit('Approved launcher master SHA-256 mismatch')
    with Image.open(SOURCE) as image:
        if image.mode != 'RGB' or image.size != (1254, 1254):
            sys.exit('Unexpected launcher master dimensions or color mode')
        for density, legacy, foreground in DENSITIES:
            for name, size in (('ic_launcher.png', legacy), ('ic_launcher_round.png', legacy), ('ic_launcher_foreground.png', foreground)):
                output = ROOT / 'android/app/src/main/res' / f'mipmap-{density}' / name
                buf = BytesIO()
                image.resize((size, size), Image.Resampling.LANCZOS).save(buf, format='PNG', optimize=True)
                data = buf.getvalue()
                if args.check:
                    if not output.exists() or output.read_bytes() != data:
                        sys.exit(f'Launcher resource differs: {output.relative_to(ROOT)}')
                else:
                    output.write_bytes(data)
                print(f'{output.relative_to(ROOT)} {size}x{size} {hashlib.sha256(data).hexdigest()}')
    print('Launcher resource check passed' if args.check else 'Launcher resources generated')


if __name__ == '__main__':
    main()
